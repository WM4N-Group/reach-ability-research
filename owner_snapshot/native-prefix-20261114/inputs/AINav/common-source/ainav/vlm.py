def parse_json(raw):
    text(raw, 'VLM response', 200000)
    raw = raw.strip()
    if raw.startswith('```'):
        lines = raw.splitlines()
        if lines[0] not in ('```json', '```') or lines[-1] != '```':
            raise ValueError('One complete JSON block required')
        raw = '\n'.join(lines[1:-1])
    def reject_constant(value):
        raise ValueError('Nonfinite JSON rejected: '+value)
    def object_pairs(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError('Duplicate JSON key rejected: '+key)
            result[key] = value
        return result
    result = json.loads(raw, parse_constant=reject_constant, object_pairs_hook=object_pairs)
    if not isinstance(result, dict):
        raise ValueError('A single role JSON object required')
    canonical(result)
    return result


class RoleRunner:
    def __init__(self, backend, journal, *, timeout_s=60., max_input_chars=120000):
        if not 0 < timeout_s <= 120:
            raise ValueError('Bounded role wall time required')
        if getattr(backend, 'kind', None) not in ('deepseek_vision_api', 'openai_compatible_vision_api', 'local_qwen_vlm'):
            raise ValueError('Production role runner requires a real verified vision backend')
        self.backend, self.journal = backend, journal
        self.timeout_s, self.max_input_chars = timeout_s, max_input_chars
        self.calls = 0

    def run(self, role, payload, observation):
        if role not in ROLE_INSTRUCTIONS:
            raise ValueError('Unknown AINav role')
        observation.verify_image()
        instruction=ROLE_INSTRUCTIONS[role]
        if payload.get('decision_layer')=='semantic_skill_intent':
            instruction+=' This is SEMANTIC INTENT MODE: admitted_first_actions is the legacy wire name for candidate INTENTS, NOT native-ready actions. Its first step must match an intent exactly, but do not enforce learned spatial starting-distance, posture or foot-load limits yourself and do not insert NAV solely to satisfy them. The independent execution judge establishes safe same-support entry and rechecks before execution. You still choose task/object/skill and obey logical scene/support prerequisites. Never treat preparation as skill or task success.'
        request = dict(role=role, system=SYSTEM, instruction=instruction,
                       payload=payload, image=observation.value['rgb'],
                       observation_sha256=observation.sha256, backend=self.backend.identity)
        if len(canonical(request)) > self.max_input_chars:
            raise ValueError('VLM input budget exceeded')
        request_ref = self.journal(dict(event='vlm_request', **request))
        start = time.monotonic()
        try:
            raw = self.backend.generate(request, timeout_s=self.timeout_s)
            elapsed = time.monotonic()-start
            if elapsed > self.timeout_s:
                raise TimeoutError('VLM role deadline expired; no dispatch')
            observation.verify_image()
            result = parse_json(raw)
            self.calls += 1
            self.journal(dict(event='vlm_response', role=role, request_ref=request_ref,
                              elapsed_wall_s=elapsed, raw_response=raw, response_sha256=sha(result),
                              backend_kind=self.backend.kind,
                              provider_metadata=getattr(self.backend, 'last_response_metadata', None)))
            return result
        except Exception as error:
            self.journal(dict(event='vlm_role_failed', role=role, request_ref=request_ref,
                              error=type(error).__name__+': '+str(error), fixed_route_fallback=False))
            raise


class QwenBackend:
    """Explicit local weights + explicit CUDA device. Scientific imports lazy.

    The caller holds the canonical GPU resource lease. A process owner enforces
    the hard wall budget; generate(max_time) itself is only a best-effort bound.
    """
    kind = 'local_qwen_vlm'

    def __init__(self, *, model_dir, weight_manifest, device='cuda:1', max_new_tokens=2048):
        model_dir, weight_manifest = Path(model_dir), Path(weight_manifest)
        if not model_dir.is_absolute() or not model_dir.is_dir() or not weight_manifest.is_file():
            raise ValueError('Existing absolute frozen model directory/manifest required')
        manifest = json.loads(weight_manifest.read_text())
        if set(manifest) != {'model_id', 'revision', 'files'} or manifest['model_id'] != 'Qwen/Qwen2.5-VL-7B-Instruct':
            raise ValueError('Explicit approved Qwen 7B weight manifest required')
        if (not isinstance(manifest['revision'], str) or len(manifest['revision']) != 40
                or any(x not in '0123456789abcdef' for x in manifest['revision'])
                or not isinstance(manifest['files'], dict) or not manifest['files']):
            raise ValueError('Pinned upstream revision and nonempty file hashes required')
        for name, digest in manifest['files'].items():
            p = model_dir/name
            if not p.resolve().is_relative_to(model_dir.resolve()) or file_sha(p) != digest:
                raise ValueError('Frozen model file changed or escaped model directory')
        actual = {str(p.relative_to(model_dir)) for p in model_dir.rglob('*') if p.is_file() and '.cache' not in p.parts}
        if actual != set(manifest['files']) or not any(n.endswith('.safetensors') for n in actual):
            raise ValueError('Manifest must cover every active model/config/tokenizer file')
        if device not in ('cuda:0', 'cuda:1') or type(max_new_tokens) is not int or not 64 <= max_new_tokens <= 4096:
            raise ValueError('Explicit admitted GPU and bounded generation required')
        self.identity = dict(model_id=manifest['model_id'], revision=manifest['revision'],
                             weight_manifest_sha256=file_sha(weight_manifest), device=device)
        self.model_dir, self.device, self.max_new_tokens = model_dir, device, max_new_tokens
        self.model = self.processor = None

    def _load(self):
        if self.model is not None:
            return
        import torch
        from transformers import AutoProcessor, Qwen2_5_VLForConditionalGeneration
        self.model = Qwen2_5_VLForConditionalGeneration.from_pretrained(
            str(self.model_dir), torch_dtype=torch.bfloat16, device_map={'': self.device},
            local_files_only=True, trust_remote_code=False).eval()
        self.processor = AutoProcessor.from_pretrained(str(self.model_dir), local_files_only=True,
                                                       trust_remote_code=False)

    def generate(self, request, *, timeout_s):
        self._load()
        import torch
        from PIL import Image
        messages = [dict(role='system', content=request['system']+'\n'+request['instruction']),
                    dict(role='user', content=[dict(type='image', image=request['image']['path']),
                         dict(type='text', text=canonical(request['payload']))])]
        formatted = self.processor.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
        with Image.open(request['image']['path']) as frame:
            if frame.size != (request['image']['width'], request['image']['height']):
                raise ValueError('Frame dimensions differ from acquisition metadata')
            image = frame.convert('RGB').copy()
        inputs = self.processor(text=[formatted], images=[image], padding=True, return_tensors='pt').to(self.device)
        if inputs.input_ids.shape[1] > 16384:
            raise ValueError('Input token budget exceeded after actual image processing')
        with torch.inference_mode():
            generated = self.model.generate(**inputs, do_sample=False, max_new_tokens=self.max_new_tokens,
                                            max_time=timeout_s)
        output = generated[:, inputs.input_ids.shape[1]:]
        if output.shape[1] >= self.max_new_tokens:
            raise ValueError('Truncated generation rejected; no schema repair/fallback')
        return self.processor.batch_decode(output, skip_special_tokens=True, clean_up_tokenization_spaces=False)[0]
